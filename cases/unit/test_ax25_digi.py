LABELS = {"Repeat": "repeat", "NoMatch": "no_match", "OwnPath": "own_path", "OwnSource": "own_source", "BadPath": "bad_path", "InternetPath": "internet_path"}


def n0call(g):
    """The vector with the N0TEST names of the rig turned back into the N0CALL names of the DV-Router fixtures."""
    sw = lambda s: s.replace("N0TEST", "N0CALL")      # noqa: E731
    return g._replace(src=sw(g.src), hops=tuple(sw(h) for h in g.hops), ours=sw(g.ours))


ALL = list(digi1.GOLDENS) + [digi1.G2B]


@pytest.mark.parametrize("g", ALL, ids=[g.id for g in ALL])
def test_the_vector_frame_is_the_hand_built_rust_golden(g):
    inp, outp, res, hop, ours = RUST_GOLDENS[g.id]
    frame = digi1.golden_frame(n0call(g))
    assert frame.hex() == inp, "%s: built %s, DV-Router's fixture %s" % (g.id, frame.hex(), inp)
    assert LABELS[res] == g.result and (hop == g.replaced or g.result != "repeat")
    assert n0call(g).ours == ours


@pytest.mark.parametrize("g", ALL, ids=[g.id for g in ALL])
def test_the_model_decides_like_the_rust_goldens(g):
    inp, outp, res, hop, ours = RUST_GOLDENS[g.id]
    result, out = digi1.decide(bytes.fromhex(inp), ours)
    assert result == LABELS[res]
    assert (out.hex() if out else "") == outp
    if out:
        assert not digi1.repeat_problems(bytes.fromhex(inp), out)
        assert ax25.diff_offsets(bytes.fromhex(inp), out)[0] >= 14 + 7 * hop


def test_g1_hop_flags_and_text():
    frame = bytes.fromhex(RUST_GOLDENS["G1"][0])
    assert ax25.hops(frame) == [("WIDE1-1", False, 3), ("WIDE2-1", False, 3)]
    assert ax25.path_text(frame) == "N0CALL-9>APRS,WIDE1-1,WIDE2-1"
    out = bytes.fromhex(RUST_GOLDENS["G1"][1])
    assert ax25.path_text(out) == "N0CALL-9>APRS,N0CALL-10*,WIDE2-1"
    assert ax25.to_tnc2(out) == "N0CALL-9>APRS,N0CALL-10*,WIDE2-1:>test"       # TNC2 form: the star after the last used hop
    assert ax25.first_unused_hop(frame) == 0 and ax25.first_unused_hop(out) == 1


def test_g10_non_contiguous_h_bits_need_the_explicit_form_tnc2_cannot_say_it():
    frame = bytes.fromhex(RUST_GOLDENS["G10"][0])
    assert ax25.hops(frame) == [("WIDE1-1", False, 3), ("N0CALL-1", True, 3)]
    assert ax25.path_text(frame) == "N0CALL-9>APRS,WIDE1-1,N0CALL-1*"
    assert ax25.to_tnc2(frame).startswith("N0CALL-9>APRS,WIDE1-1,N0CALL-1*:")
    # the TNC2 text form marks every hop up to the star as used, so it builds a different frame
    assert ax25.from_tnc2("N0CALL-9>APRS,WIDE1-1,N0CALL-1*:>test", cr_src=False) != frame


def test_build_ui_round_trips_through_parse_frame():
    frame = ax25.build_ui("APRS-3", "N0TEST-9", [("N0TEST-1", True), ("WIDE1-1", False, 0), "WIDE2-2"], ">round trip", cr_src=False)
    f = ax25.parse_frame(frame)
    assert (f["dest"]["text"], f["src"]["text"], f["control"], f["pid"], f["info"]) == ("APRS-3", "N0TEST-9", 0x03, 0xF0, b">round trip")
    assert [(d["text"], d["bit7"], d["reserved"], d["last"]) for d in f["digis"]] == [
        ("N0TEST-1", True, 3, False), ("WIDE1-1", False, 0, False), ("WIDE2-2", False, 3, True)]
    assert f["dest"]["bit7"] is True and f["src"]["bit7"] is False
    assert ax25.hops(frame) == [("N0TEST-1", True, 3), ("WIDE1-1", False, 0), ("WIDE2-2", False, 3)]


def test_build_ui_without_hops_sets_the_extension_bit_on_the_source_and_matches_from_tnc2():
    frame = ax25.build_ui("APRS", "N0TEST-9", [], b">x")
    assert ax25.parse_frame(frame)["src"]["last"] is True
    assert frame == ax25.from_tnc2("N0TEST-9>APRS:>x")
    both = ax25.build_ui("APRS", "N0TEST-9", ["WIDE1-1", "WIDE2-1"], b">x")
    assert both == ax25.from_tnc2("N0TEST-9>APRS,WIDE1-1,WIDE2-1:>x")
    used = ax25.build_ui("APRS", "N0TEST-9", [("A1", True), ("WIDE1-1", True)], b">x")
    assert used == ax25.from_tnc2("N0TEST-9>APRS,A1,WIDE1-1*:>x")


def test_build_ui_refuses_nine_hops_and_bad_calls():
    with pytest.raises(ValueError):
        ax25.build_ui("APRS", "N0TEST-9", ["WIDE1-1"] * 9, b"x")
    with pytest.raises(ValueError):
        ax25.build_ui("APRS", "n0test", [], b"x")
    with pytest.raises(ValueError):
        ax25.build_ui("APRS", "N0TEST-16", [], b"x")


def test_replace_hop_changes_exactly_the_seven_bytes_and_keeps_the_extension_bit():
    frame = ax25.build_ui("APRS", "N0TEST-9", ["WIDE1-1", "WIDE2-1"], b">x", cr_src=False)
    out = ax25.replace_hop(frame, 0, "N0TEST-10")
    diff = ax25.diff_offsets(frame, out)
    assert diff and 14 <= diff[0] and diff[-1] <= 20          # inside the seven bytes of hop 0 (a letter two calls share is not a difference)
    assert ax25.hops(out) == [("N0TEST-10", True, 3), ("WIDE2-1", False, 3)]
    last = ax25.replace_hop(frame, 1, "N0TEST")
    assert ax25.parse_frame(last)["digis"][1]["last"] is True and ax25.hops(last)[1] == ("N0TEST", True, 3)
    assert ax25.replace_hop(last, 1, "WIDE1-1") != last
    with pytest.raises(IndexError):
        ax25.replace_hop(frame, 2, "N0TEST-10")
    with pytest.raises(ValueError):
        ax25.diff_offsets(frame, frame + b"x")


def test_replace_hop_sets_the_reserved_bits_of_the_hop_only():
    frame = ax25.build_ui("APRS", "N0TEST-9", [("WIDE1-1", False, 0), ("WIDE2-1", False, 0)], b">x", cr_src=False)
    out = ax25.replace_hop(frame, 0, "N0TEST-10")
    assert ax25.hops(out) == [("N0TEST-10", True, 3), ("WIDE2-1", False, 0)]
    assert set(ax25.diff_offsets(frame, out)) <= set(range(14, 21)) and 20 in ax25.diff_offsets(frame, out)
