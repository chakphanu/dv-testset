#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Write local, gitignored rig settings to .local/rig.env (mode 600):
#   DVT_IAX_SECRET   random IAX2 secret shared by the AllStar node and tester
# An existing file is kept unless --force is given. The secret is never printed.
set -euo pipefail

. "$(dirname "$0")/lib/env.sh"
cd "$DVT_ROOT"

force=0
case "${1:-}" in
  --force) force=1 ;;
  '') ;;
  *) echo "usage: $0 [--force]" >&2; exit 2 ;;
esac

env_file=".local/rig.env"
if [ -f "$env_file" ] && [ "$force" = 0 ]; then
  echo "gen-local: $env_file exists, kept (use --force to replace)"
  exit 0
fi

mkdir -p .local
chmod 700 .local
umask 077
secret="$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"
tmp="$(mktemp "$env_file.XXXXXX")"
printf '# generated by scripts/gen-local.sh; never commit\nDVT_IAX_SECRET=%s\n' "$secret" > "$tmp"
chmod 600 "$tmp"
mv -f "$tmp" "$env_file"
echo "gen-local: wrote $env_file (mode 600)"
