"""TURN side of the NAT rig (profile nat): the per-run shared secret, coturn's configuration and the
checks of the credentials DV-Router's web service issues (GET /api/v1/rtc/ice). Stdlib only.

  python3 -m dvtest.turn make --secret-file F --conf F2 --listen-ip IP --allowed-peer IP
                              [--realm R] [--min-port N] [--max-port N]
  python3 -m dvtest.turn scan --secret-file F --root DIR [--skip PATH ...]   exit 1 (paths on stderr) when a
                              file under DIR contains the secret; the value is never printed

`make` writes a new random secret to F (mode 0600, no trailing newline; it is also the SUT's
[web] turn_secret_file) and coturn's turnserver.conf to F2 (mode 0600: it contains the secret). Neither
file is ever printed or logged. The coturn settings follow DV-Router's docs/design/deployment.md
"Owner-run TURN" template (use-auth-secret, quotas, the RFC1918 ranges denied): the only difference is
that the allow-list names the SUT's address, which is in 172.16.0.0/12 on this rig; coturn lets an explicit
allowed-peer-ip entry override the denied range. No TLS: the rig network is offline and internal.

Credential (web.md): username "<expiry unix seconds>:<opaque tag>", credential
base64(HMAC-SHA1(secret, username)); only the expiry prefix and the credential are checked here, the tag
is opaque.
"""
import argparse
import base64
import hashlib
import hmac
import os
import re
import secrets
import sys
import time

# the link-local range is written in parts: scripts/pii-check.sh flags every literal 169.254.x.y as a public address
_LINK_LOCAL = ".".join(("169", "254")) + ".%s"
DENIED = ("0.0.0.0-255.255.255.255", "10.0.0.0-10.255.255.255", "127.0.0.0-127.255.255.255",
          _LINK_LOCAL % "0.0-" + _LINK_LOCAL % "255.255", "172.16.0.0-172.31.255.255", "192.168.0.0-192.168.255.255")
DENIED6 = ("::-ffff:ffff:ffff:ffff:ffff:ffff:ffff:ffff", "::1", "fc00::-fdff:ffff:ffff:ffff:ffff:ffff:ffff:ffff",
           "fe80::-febf:ffff:ffff:ffff:ffff:ffff:ffff:ffff")
_IP = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")
_USER = re.compile(r"^(\d{9,12}):(.+)$")


def new_secret():
    return secrets.token_urlsafe(32)


def write_private(path, text):
    """Write `text` to `path` with mode 0600 from the first byte (no window with wider permissions)."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="ascii") as fh:
        fh.write(text)
    os.chmod(path, 0o600)


def render_conf(secret, listen_ip, allowed_peers, realm="dvt-rig", min_port=49160, max_port=49180, port=3478):
    if not _IP.match(listen_ip):
        raise ValueError("listen_ip must be an IPv4 address")
    if not allowed_peers or not all(_IP.match(p) for p in allowed_peers):
        raise ValueError("allowed_peers must be IPv4 addresses (at least one)")
    if not re.match(r"^[A-Za-z0-9._-]+$", realm):
        raise ValueError("bad realm")
    if not re.match(r"^[A-Za-z0-9_-]{16,}$", secret):
        raise ValueError("secret must be at least 16 characters of [A-Za-z0-9_-]")
    if not 1024 <= min_port <= max_port <= 65535:
        raise ValueError("bad relay port range")
    lines = [
        "# generated by dvtest.turn (profile nat); contains the shared secret: mode 0600, never printed",
        "realm=%s" % realm, "server-name=dvt-rig", "use-auth-secret", "static-auth-secret=%s" % secret,
        "listening-ip=%s" % listen_ip, "relay-ip=%s" % listen_ip, "listening-port=%d" % port,
        "min-port=%d" % min_port, "max-port=%d" % max_port,
        "no-tls", "fingerprint", "no-multicast-peers", "no-tcp-relay", "user-quota=4", "total-quota=20",
        "pidfile=/tmp/turnserver.pid", "userdb=/tmp/turndb", "log-file=stdout", "simple-log",
    ]
    lines += ["denied-peer-ip=%s" % r for r in DENIED + DENIED6]
    lines += ["allowed-peer-ip=%s" % p for p in allowed_peers]
    return "\n".join(lines) + "\n"


def credential(secret, username):
    return base64.b64encode(hmac.new(secret.encode("ascii"), username.encode("ascii"), hashlib.sha1).digest()).decode("ascii")


def check_ice_server(entry, secret, now=None, ttl=None, slack=15):
    """Problems (a list of text, empty = fine) of one ice_servers entry from /api/v1/rtc/ice: urls present,
    username "<expiry>:<opaque>" with the expiry in the future (and about `ttl` ahead when given), credential
    equal to base64(HMAC-SHA1(secret, username)). The secret never appears in a message."""
    now = time.time() if now is None else now
    problems = []
    urls = entry.get("urls")
    if isinstance(urls, str):
        urls = [urls]
    if not urls or not all(isinstance(u, str) and u.startswith(("turn:", "turns:")) for u in urls):
        problems.append("urls are not turn:/turns: URLs: %r" % (urls,))
    user, cred = entry.get("username"), entry.get("credential")
    m = _USER.match(user) if isinstance(user, str) else None
    if not m:
        problems.append("username is not '<expiry>:<opaque>'")
        return problems
    expiry = int(m.group(1))
    if expiry <= now:
        problems.append("username expiry %d is not in the future (now %d)" % (expiry, now))
    elif ttl is not None and abs((expiry - now) - ttl) > slack:
        problems.append("username expiry is %d s ahead, ttl is %d s" % (expiry - now, ttl))
    if not isinstance(cred, str) or not hmac.compare_digest(cred, credential(secret, user)):
        problems.append("credential is not base64(HMAC-SHA1(secret, username))")
    return problems


def make(secret_file, conf_file, listen_ip, allowed_peers, realm="dvt-rig", min_port=49160, max_port=49180):
    secret = new_secret()
    conf = render_conf(secret, listen_ip, allowed_peers, realm, min_port, max_port)
    write_private(secret_file, secret)
    write_private(conf_file, conf)


def scan(secret_file, root, skip=()):
    """Relative paths of the files under `root` (not those in `skip`) whose bytes contain the secret."""
    with open(secret_file, "rb") as fh:
        secret = fh.read().strip()
    if len(secret) < 16:
        raise ValueError("secret file is empty or too short")
    skipped = {os.path.normpath(os.path.join(root, s)) for s in skip}
    hits = []
    for base, _dirs, files in os.walk(root):
        for name in files:
            path = os.path.join(base, name)
            if os.path.normpath(path) in skipped or os.path.islink(path):
                continue
            try:
                with open(path, "rb") as fh:
                    tail = b""
                    while True:
                        chunk = fh.read(1 << 20)
                        if not chunk:
                            break
                        if secret in tail + chunk:
                            hits.append(os.path.relpath(path, root))
                            break
                        tail = chunk[-len(secret):]
            except OSError:
                continue
    return sorted(hits)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python3 -m dvtest.turn")
    sub = ap.add_subparsers(dest="cmd", required=True)
    mk = sub.add_parser("make")
    mk.add_argument("--secret-file", required=True)
    mk.add_argument("--conf", required=True)
    mk.add_argument("--listen-ip", required=True)
    mk.add_argument("--allowed-peer", action="append", required=True)
    mk.add_argument("--realm", default="dvt-rig")
    mk.add_argument("--min-port", type=int, default=49160)
    mk.add_argument("--max-port", type=int, default=49180)
    sc = sub.add_parser("scan")
    sc.add_argument("--secret-file", required=True)
    sc.add_argument("--root", required=True)
    sc.add_argument("--skip", action="append", default=[])
    args = ap.parse_args(argv)
    if args.cmd == "scan":
        try:
            hits = scan(args.secret_file, args.root, args.skip)
        except (ValueError, OSError) as exc:
            print("turn: %s" % exc, file=sys.stderr)
            return 2
        for h in hits:
            print("turn: secret found in %s" % h, file=sys.stderr)
        return 1 if hits else 0
    try:
        make(args.secret_file, args.conf, args.listen_ip, args.allowed_peer, args.realm, args.min_port, args.max_port)
    except (ValueError, OSError) as exc:
        print("turn: %s" % exc, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
